import { inflate } from 'pako'
import { DICT_DATA_B64 } from './dict-data'
import { KUROMOJI_DICT_FILES, type DictFileMap } from './loadDict.types'

export type { DictFileMap } from './loadDict.types'

/**
 * Decode a base64 string into an ArrayBuffer.
 *
 * `globalThis.atob` is available on Hermes and on every modern engine,
 * but Hermes returns a binary string (one char per byte). We pull each
 * char's code into a Uint8Array.
 */
function base64ToArrayBuffer(b64: string): ArrayBuffer {
  const binary = globalThis.atob(b64)
  const len = binary.length
  const bytes = new Uint8Array(len)
  for (let i = 0; i < len; i++) bytes[i] = binary.charCodeAt(i)
  return bytes.buffer
}

/**
 * Returns the kuromoji IPA dictionary as a Map<filename, ArrayBuffer>.
 *
 * The dict bytes are baked into the JS bundle as base64-encoded gzip
 * strings (auto-generated by scripts/copy-dict.mjs). At runtime we
 * decode the base64 and gunzip with pako. **No file IO, no asset
 * resolution, no network — guaranteed offline behaviour.**
 *
 * Why this rather than `Asset.fromModule()` + `expo-file-system`:
 *
 *   React Native's asset resource identifier for our `.dat.gz` files
 *   becomes `__packages_core_assets_dict_basedat` (the `__` is part of
 *   the path-encoding scheme). Android resource names that start with
 *   underscores fail to resolve via `Resources.getIdentifier()`, so
 *   `Asset.downloadAsync()` throws `Resources.NotFoundException` —
 *   useQuery retries forever and the user sees an infinite loading
 *   spinner. Inlining bypasses the entire asset resolution chain.
 *
 * Memory cost: the base64 strings live as JS literals (~23 MB) and the
 * decoded gzipped bytes live as ArrayBuffers (~17 MB) until the
 * tokenizer build runs and we drop both. After build completes, only
 * the decompressed dict structures (~95 MB) are retained — the same
 * footprint as the original kuromoji.js used.
 */
export async function loadDictFiles(): Promise<DictFileMap> {
  const map: DictFileMap = new Map()
  for (const name of KUROMOJI_DICT_FILES) {
    const b64 = DICT_DATA_B64[name]
    if (!b64) throw new Error(`Missing inlined dict data: ${name}`)
    const gz = base64ToArrayBuffer(b64)
    const raw = inflate(new Uint8Array(gz))
    // Copy to a fresh ArrayBuffer at offset 0 so kuromoji's typed-array
    // views (Int32Array etc.) line up correctly.
    const out = new Uint8Array(raw.byteLength)
    out.set(raw)
    map.set(name, out.buffer)
  }
  return map
}
