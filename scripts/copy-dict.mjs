/**
 * Materialise the kuromoji IPA dictionary for every workspace that
 * needs them, in two complementary forms:
 *
 *   1. Raw `.dat.gz` files copied into apps/mobile/public/dict/ — the web
 *      build serves these via fetch('/dict/<name>.dat.gz'). The browser
 *      automatically decompresses them on the wire.
 *   2. Base64-encoded TypeScript modules under
 *      packages/core/src/tokenizer/dict-data/ — the native build imports
 *      these directly. Inlining the bytes in JS sidesteps RN's broken
 *      resource resolution for non-image binary assets (the asset
 *      identifier becomes `__packages_core_assets_dict_basedat`, whose
 *      leading underscores prevent Android's R.getIdentifier() from
 *      finding the resource — `Asset.fromModule().downloadAsync()` then
 *      hangs forever).
 *
 * The dict bytes ship gzipped (17 MB total) rather than decompressed
 * (95 MB) so the JS bundle stays manageable. Runtime decompression uses
 * pako (~45 KB, ~150 ms for the full IPA dict) and is shared between web
 * and native via `buildTokenizer.ts`.
 *
 * Runs at workspace root postinstall so a single `npm install` wires up
 * everything. Skips silently when the source dir is missing.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const source = join(root, 'node_modules', 'kuromoji', 'dict')
const webPublic = join(root, 'apps', 'mobile', 'public', 'dict')
const nativeData = join(root, 'packages', 'core', 'src', 'tokenizer', 'dict-data')

if (!existsSync(source)) {
  console.warn(`[copy-dict] ${source} missing; skipping`)
  process.exit(0)
}

const files = readdirSync(source).filter((f) => f.endsWith('.dat.gz'))

// 1. Web: raw copies of the .dat.gz files.
mkdirSync(webPublic, { recursive: true })
for (const f of files) {
  const from = join(source, f)
  const to = join(webPublic, f)
  writeFileSync(to, readFileSync(from))
}
console.log(`[copy-dict] ${webPublic} (${files.length} raw .gz files)`)

// 2. Native: base64-encoded TypeScript modules. Each module exports a
// single base64 string; the loader decodes them at startup. We rebuild
// the directory from scratch each time — cleaner than trying to track
// stale files when the source set changes.
if (existsSync(nativeData)) rmSync(nativeData, { recursive: true })
mkdirSync(nativeData, { recursive: true })

const indexExports = []
let totalBytes = 0
for (const f of files) {
  const bytes = readFileSync(join(source, f))
  totalBytes += bytes.length
  const b64 = bytes.toString('base64')
  // Identifier-safe TS module name: `base_dat_gz` → `BASE_DAT_GZ`
  const id = f.replace(/[^a-z0-9]/gi, '_').toUpperCase()
  // One file per module so Hermes can lazily skip-parse each string until
  // the loader actually imports it.
  writeFileSync(
    join(nativeData, `${f.replace(/[^a-z0-9.]/gi, '_')}.ts`),
    `// Auto-generated by scripts/copy-dict.mjs — do not edit.\n` +
    `// Source: node_modules/kuromoji/dict/${f}\n` +
    `// Bytes: ${bytes.length}\n` +
    `export const ${id} = '${b64}'\n`
  )
  indexExports.push({ filename: f, id, modulePath: `./${f.replace(/[^a-z0-9.]/gi, '_')}` })
}

writeFileSync(
  join(nativeData, 'index.ts'),
  '// Auto-generated by scripts/copy-dict.mjs — do not edit.\n' +
  '// Maps each kuromoji dict filename to its base64-encoded gzipped bytes.\n\n' +
  indexExports.map((e) => `import { ${e.id} } from '${e.modulePath}'`).join('\n') + '\n\n' +
  'export const DICT_DATA_B64: Record<string, string> = {\n' +
  indexExports.map((e) => `  '${e.filename}': ${e.id},`).join('\n') + '\n' +
  '}\n'
)

console.log(`[copy-dict] ${nativeData} (${files.length} base64 .ts modules, ${(totalBytes / 1024 / 1024).toFixed(1)} MB raw)`)
